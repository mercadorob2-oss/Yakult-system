// Run against the isolated fixture host, never the production portal.
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const { chromium } = require(path.join(os.tmpdir(), 'yakult-learning-qa', 'node_modules', 'playwright'));

(async () => {
    const cachedBrowser = path.join(process.env.LOCALAPPDATA || '', 'ms-playwright', 'chromium-1228', 'chrome-win64', 'chrome.exe');
    const browser = await chromium.launch({ headless: true, ...(fs.existsSync(cachedBrowser) ? { executablePath: cachedBrowser } : {}) });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    const page = await context.newPage();
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const base = 'http://127.0.0.1:5187';
    const output = path.join(os.tmpdir(), 'yakult-learning-qa', 'screenshots');
    fs.mkdirSync(output, { recursive: true });
    async function visit(url) {
        const response = await page.goto(base + url);
        assert.equal(response.status(), 200, (await page.locator('body').innerText()).slice(0, 1800));
    }
    async function fits(label) {
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), label + ': horizontal overflow');
    }
    await visit('/Public/Learning');
    assert.equal(await page.locator('.academy-card').count(), 12);
    assert.equal(new Set(await page.locator('.academy-card h3').allTextContents()).size, 12);
    await fits('Desktop library');
    await page.screenshot({ path: path.join(output, 'desktop-library.png'), fullPage: true });
    await page.getByRole('link', { name: 'Next →', exact: true }).click();
    assert.match(await page.locator('.academy-pagination').innerText(), /Page 2 of 3/);
    await page.getByRole('searchbox', { name: 'Find your next lesson' }).fill('nonexistent-lesson');
    await page.getByRole('button', { name: 'Find learning' }).click();
    await page.waitForURL(/q=nonexistent-lesson/);
    await page.getByRole('heading', { name: 'No learning resources found.' }).waitFor({ state: 'visible' });
    assert.equal(await page.locator('.academy-card').count(), 0);
    assert.ok(await page.getByRole('heading', { name: 'No learning resources found.' }).isVisible());
    await visit('/content/cybersecurity-essentials');
    await page.screenshot({ path: path.join(output, 'desktop-course.png'), fullPage: true });
    await page.locator('#academyStart').click();
    assert.equal(await page.locator('[data-lesson]:visible').count(), 1);
    await page.locator('[data-lesson]:visible [data-complete]').click();
    assert.ok(await page.getByRole('heading', { name: 'Make the safe choice' }).isVisible());
    await page.locator('[data-lesson]:visible [data-complete]').click();
    assert.match(await page.locator('.academy-quiz-feedback:visible').innerText(), /Answer this practice/);
    await page.getByLabel('Reply with the password').check();
    await page.getByRole('button', { name: 'Check answer' }).click();
    assert.match(await page.locator('.academy-quiz-feedback:visible').innerText(), /Try again/);
    await page.getByLabel('Verify and report through an official channel').check();
    await page.getByRole('button', { name: 'Check answer' }).click();
    assert.match(await page.locator('.academy-quiz-feedback:visible').innerText(), /Correct/);
    await page.locator('[data-lesson]:visible [data-complete]').click();
    await page.locator('[data-lesson]:visible [data-complete]').click();
    assert.ok(await page.locator('#academyFinished').isVisible());
    assert.match(await page.locator('#academyProgressLabel').innerText(), /3 of 3/);
    await visit('/Public/Learning');
    assert.match(await page.locator('[data-course-key]:not([data-course-key=""]) [data-course-status]').innerText(), /3 of 3 complete/);
    await visit('/Public/MyLearning');
    assert.ok(await page.locator('#academyMyLearning').isVisible());
    assert.match(await page.locator('.academy-browser-course').innerText(), /Cybersecurity essentials[\s\S]*3 of 3/);
    assert.ok(await page.locator('.my-learning-empty').isHidden());
    await visit('/Admin/LearningContent?legacy=true');
    assert.ok(await page.locator('#courseBuilderLaunch').isVisible());
    await page.locator('#enableCourseBuilder').click();
    assert.ok(await page.locator('#courseBuilder').isVisible());
    const converted = await page.locator('#body').inputValue();
    assert.match(converted, /Before you start/);
    assert.equal(await page.locator('#contentType').inputValue(), 'Course');
    await page.locator('#builderDuplicateLesson').click();
    let doc = JSON.parse((await page.locator('#body').inputValue()).split('\n').slice(1).join('\n'));
    assert.equal(doc.modules[0].lessons.length, 2);
    assert.notEqual(doc.modules[0].lessons[0].id, doc.modules[0].lessons[1].id);
    await page.locator('#builderAddModule').click();
    await page.locator('#builderLessonTitle').fill('Practice a safe response');
    await page.locator('[data-lesson-template="awareness"]').click();
    assert.equal(await page.locator('.builder-block').count(), 3);
    await page.locator('#builderBlockType').selectOption('video');
    await page.locator('#builderAddBlock').click();
    let draftRequests = 0;
    const countSave = request => { if (request.url().endsWith('/LearningContent/Save')) draftRequests++; };
    page.on('request', countSave);
    await page.locator('#saveDraftBtn').click();
    await page.locator('.portal-toast').last().waitFor();
    assert.equal(draftRequests, 0, 'Incomplete media is rejected before a save request');
    page.off('request', countSave);
    await page.locator('.builder-block').last().getByRole('button', { name: 'Remove', exact: true }).click();
    await page.locator('#builderBlockType').selectOption('image');
    await page.locator('#builderAddBlock').click();
    await page.locator('.builder-block').last().getByLabel('Or choose a file').setInputFiles({ name: 'screen.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jp9sAAAAASUVORK5CYII=', 'base64') });
    await page.locator('.builder-block').last().getByRole('button', { name: 'Upload file' }).click();
    await page.getByText('File ready.', { exact: true }).waitFor();
    assert.match(await page.locator('#body').inputValue(), /\/media\/learning\/fixtures\/uploaded.png/);
    await fits('Desktop builder');
    await page.screenshot({ path: path.join(output, 'desktop-builder.png'), fullPage: true });
    await Promise.all([page.waitForNavigation(), page.locator('#saveDraftBtn').click()]);
    assert.ok(await page.locator('#courseBuilder').isVisible());
    doc = JSON.parse((await page.locator('#body').inputValue()).split('\n').slice(1).join('\n'));
    assert.equal(doc.modules.length, 2, 'Course survives the existing Save draft / reload flow');
    assert.equal(doc.modules[1].lessons[0].blocks[2].type, 'quiz');
    for (const width of [390, 320]) {
        await page.setViewportSize({ width, height: 844 });
        await visit('/Public/Learning'); await fits('Mobile library ' + width);
        await visit('/content/cybersecurity-essentials'); await fits('Mobile course ' + width);
        await page.locator('#academyStart').click(); await fits('Mobile lesson ' + width);
        if (width === 390) await page.screenshot({ path: path.join(output, 'mobile-lesson.png'), fullPage: true });
        await visit('/Admin/LearningContent'); await fits('Mobile builder ' + width);
        if (width === 390) await page.screenshot({ path: path.join(output, 'mobile-builder.png'), fullPage: true });
    }
    await visit('/content/system-access');
    assert.ok(await page.locator('.article-body').getByRole('heading', { name: 'Before you start' }).isVisible());
    assert.equal(await page.locator('#academyCourse').count(), 0, 'Legacy content retains its reader');
    assert.deepEqual(errors, [], 'No JavaScript page errors');
    await context.close();
    const restricted = await browser.newContext();
    const restrictedPage = await restricted.newPage();
    await restrictedPage.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked'); }; });
    await restrictedPage.goto(base + '/content/cybersecurity-essentials');
    assert.match(await restrictedPage.locator('#academyStorageNote').innerText(), /storage is unavailable/);
    await browser.close();
    console.log('PASS: catalog paging/search, course navigation/quizzes/completion, My Learning, legacy conversion, media validation/upload, authoring save/reload, storage fallback, legacy reader, and layouts at 1440/390/320px.');
    console.log('Screenshots: ' + output);
})().catch(error => { console.error(error); process.exit(1); });
